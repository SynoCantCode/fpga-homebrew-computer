; the mouse pointer, change its look here
; graphics_init copies it to POINTER_PICTURE and POINTER_COLOUR_1-3
; 16 x 16 dots, one .word per row, row 0 at the top
; 2 bits per dot, dot 0 (the left) is bits 1-0, dot 15 is bits 31-30
; 0 = see-through   1 = colour 1   2 = colour 2   3 = colour 3
; in the drawings . = 0, # = 1 the outline, o = 2 the inside
; the hot spot is the top-left dot, POINTER_X, POINTER_Y

